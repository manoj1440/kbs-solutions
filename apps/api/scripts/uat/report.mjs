// Writes DOCS/qa/uat-01-checks.md from the last run's results (every check, grouped by stage).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const results = JSON.parse(readFileSync(join(process.env.UAT_OUT ?? join(HERE, '.out'), 'results.json'), 'utf8'));
const stages = [...new Set(results.map((r) => r.stage))];
const pass = results.filter((r) => r.pass).length;
const fail = results.length - pass;
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
let md = `# UAT-01 — every check of the last run\n\nGenerated by \`apps/api/scripts/uat/report.mjs\`. Plan: [uat-01-end-to-end-plan.md](./uat-01-end-to-end-plan.md). Findings and fixes: [uat-01-results.md](./uat-01-results.md).\n\n`;
md += `**${results.length} checks: ${pass} passed, ${fail} failed.**\n\n| Stage | Checks | Passed | Failed |\n|---|---|---|---|\n`;
for (const s of stages) { const rs = results.filter((r) => r.stage === s); md += `| ${s} | ${rs.length} | ${rs.filter((r) => r.pass).length} | ${rs.filter((r) => !r.pass).length} |\n`; }
if (fail) { md += `\n## Failed\n| Id | Check | Detail |\n|---|---|---|\n`; for (const r of results.filter((x) => !x.pass)) md += `| ${r.id} | ${esc(r.title)} | ${esc(r.detail).slice(0, 300)} |\n`; }
for (const s of stages) { md += `\n## ${s}\n| Id | Check | Result |\n|---|---|---|\n`; for (const r of results.filter((x) => x.stage === s)) md += `| ${r.id} | ${esc(r.title)} | ${r.pass ? 'pass' : '**FAIL**'} |\n`; }
writeFileSync(join(HERE, '../../../../DOCS/qa/uat-01-checks.md'), md);
console.log(`\n${results.length} checks: ${pass} passed, ${fail} failed → DOCS/qa/uat-01-checks.md`);
process.exit(fail ? 1 : 0);
